"""
parser.py - LL(1) Deterministic Recursive Descent Parser for DevLang.
Consumes tokens generated by lexer.py and constructs an Abstract Syntax Tree (AST).
"""

from dataclasses import dataclass
from typing import List, Optional, Tuple
from tokens import Token, TokenType
from ast_nodes import (
    ASTNode, ProgramNode, VarDeclNode, AssignNode,
    IfNode, WhileNode, PrintNode, BinaryOpNode,
    UnaryOpNode, LiteralNode, VarRefNode
)


@dataclass
class SyntaxErrorRecord:
    message: str
    line: int
    column: int

    def __str__(self) -> str:
        return f"[SYNTAX_ERROR] Line {self.line}, Column {self.column}: {self.message}"


class Parser:
    def __init__(self, tokens: List[Token]):
        self.tokens: List[Token] = tokens
        self.current: int = 0
        self.errors: List[SyntaxErrorRecord] = []

    # Helper Navigation Primitives
    def _is_at_end(self) -> bool:
        return self._peek().type == TokenType.EOF

    def _peek(self) -> Token:
        return self.tokens[self.current]

    def _previous(self) -> Token:
        return self.tokens[self.current - 1]

    def _advance(self) -> Token:
        if not self._is_at_end():
            self.current += 1
        return self._previous()

    def _check(self, token_type: TokenType) -> bool:
        # FIXED: Removed the premature 'if self._is_at_end(): return False' 
        # so that TokenType.EOF can be checked and consumed correctly at the end of the file.
        return self._peek().type == token_type

    def _match(self, *types: TokenType) -> bool:
        for t_type in types:
            if self._check(t_type):
                self._advance()
                return True
        return False

    def _consume(self, token_type: TokenType, message: str) -> Token:
        if self._check(token_type):
            return self._advance()
        
        tok = self._peek()
        err = SyntaxErrorRecord(f"{message} (found '{tok.value}' [{tok.type.name}])", tok.line, tok.column)
        self.errors.append(err)
        raise SyntaxError(str(err))

    def _synchronize(self) -> None:
        """Error recovery mechanism to skip tokens until reaching a statement boundary."""
        self._advance()
        while not self._is_at_end():
            if self._previous().type == TokenType.SEMICOLON:
                return
            if self._peek().type in (
                TokenType.KEYWORD_INT, TokenType.KEYWORD_FLOAT,
                TokenType.KEYWORD_IF, TokenType.KEYWORD_WHILE,
                TokenType.KEYWORD_PRINT, TokenType.KEYWORD_END,
                TokenType.RBRACE
            ):
                return
            self._advance()

    # Entry point
    def parse(self) -> Tuple[Optional[ProgramNode], List[SyntaxErrorRecord]]:
        self.errors.clear()
        statements: List[ASTNode] = []
        
        # Check START boundary
        try:
            start_tok = self._consume(TokenType.KEYWORD_START, "Expected 'START' at beginning of program")
        except SyntaxError:
            return None, self.errors

        # Parse Statement List
        while not self._check(TokenType.KEYWORD_END) and not self._is_at_end():
            try:
                stmt = self._parse_statement()
                if stmt:
                    statements.append(stmt)
            except SyntaxError:
                self._synchronize()

        # Check END boundary
        try:
            self._consume(TokenType.KEYWORD_END, "Expected 'END' at end of program")
            self._consume(TokenType.EOF, "Unexpected tokens after 'END'")
        except SyntaxError:
            pass

        if self.errors:
            return None, self.errors

        return ProgramNode(line=start_tok.line, column=start_tok.column, statements=statements), []

    # Statement Parsing
    def _parse_statement(self) -> ASTNode:
        if self._check(TokenType.KEYWORD_INT) or self._check(TokenType.KEYWORD_FLOAT):
            return self._parse_var_decl_statement()
        elif self._check(TokenType.KEYWORD_IF):
            return self._parse_if_statement()
        elif self._check(TokenType.KEYWORD_WHILE):
            return self._parse_while_statement()
        elif self._check(TokenType.KEYWORD_PRINT):
            return self._parse_print_statement()
        elif self._check(TokenType.IDENTIFIER):
            return self._parse_assign_statement()
        else:
            tok = self._peek()
            err = SyntaxErrorRecord(f"Unexpected token '{tok.value}' at statement start", tok.line, tok.column)
            self.errors.append(err)
            raise SyntaxError(str(err))

    def _parse_var_decl_statement(self) -> VarDeclNode:
        type_tok = self._advance()
        type_name = type_tok.value
        
        id_tok = self._consume(TokenType.IDENTIFIER, "Expected identifier in variable declaration")
        var_name = id_tok.value
        
        initializer: Optional[ASTNode] = None
        if self._match(TokenType.OP_ASSIGN):
            initializer = self._parse_expression()
            
        self._consume(TokenType.SEMICOLON, "Expected ';' after variable declaration")
        return VarDeclNode(
            line=type_tok.line,
            column=type_tok.column,
            type_name=type_name,
            name=var_name,
            initializer=initializer
        )

    def _parse_assign_statement(self) -> AssignNode:
        id_tok = self._consume(TokenType.IDENTIFIER, "Expected identifier in assignment")
        var_name = id_tok.value
        
        self._consume(TokenType.OP_ASSIGN, "Expected '=' in assignment statement")
        val_expr = self._parse_expression()
        self._consume(TokenType.SEMICOLON, "Expected ';' after assignment statement")
        
        return AssignNode(
            line=id_tok.line,
            column=id_tok.column,
            name=var_name,
            value=val_expr
        )

    def _parse_if_statement(self) -> IfNode:
        if_tok = self._consume(TokenType.KEYWORD_IF, "Expected 'if'")
        self._consume(TokenType.LPAREN, "Expected '(' after 'if'")
        cond_expr = self._parse_expression()
        self._consume(TokenType.RPAREN, "Expected ')' after condition")
        
        self._consume(TokenType.LBRACE, "Expected '{' before then block")
        then_stmts = self._parse_block_statements()
        self._consume(TokenType.RBRACE, "Expected '}' after then block")
        
        else_stmts: Optional[List[ASTNode]] = None
        if self._match(TokenType.KEYWORD_ELSE):
            self._consume(TokenType.LBRACE, "Expected '{' before else block")
            else_stmts = self._parse_block_statements()
            self._consume(TokenType.RBRACE, "Expected '}' after else block")
            
        return IfNode(
            line=if_tok.line,
            column=if_tok.column,
            condition=cond_expr,
            then_block=then_stmts,
            else_block=else_stmts
        )

    def _parse_while_statement(self) -> WhileNode:
        while_tok = self._consume(TokenType.KEYWORD_WHILE, "Expected 'while'")
        self._consume(TokenType.LPAREN, "Expected '(' after 'while'")
        cond_expr = self._parse_expression()
        self._consume(TokenType.RPAREN, "Expected ')' after condition")
        
        self._consume(TokenType.LBRACE, "Expected '{' before while body")
        body_stmts = self._parse_block_statements()
        self._consume(TokenType.RBRACE, "Expected '}' after while body")
        
        return WhileNode(
            line=while_tok.line,
            column=while_tok.column,
            condition=cond_expr,
            body=body_stmts
        )

    def _parse_print_statement(self) -> PrintNode:
        print_tok = self._consume(TokenType.KEYWORD_PRINT, "Expected 'print'")
        self._consume(TokenType.LPAREN, "Expected '(' after 'print'")
        expr = self._parse_expression()
        self._consume(TokenType.RPAREN, "Expected ')' after print expression")
        self._consume(TokenType.SEMICOLON, "Expected ';' after print statement")
        
        return PrintNode(
            line=print_tok.line,
            column=print_tok.column,
            expr=expr
        )

    def _parse_block_statements(self) -> List[ASTNode]:
        stmts: List[ASTNode] = []
        while not self._check(TokenType.RBRACE) and not self._check(TokenType.KEYWORD_END) and not self._is_at_end():
            try:
                stmt = self._parse_statement()
                if stmt:
                    stmts.append(stmt)
            except SyntaxError:
                self._synchronize()
        return stmts

    # Expression Parsing (Precedence Cascade)
    def _parse_expression(self) -> ASTNode:
        return self._parse_relational_expression()

    def _parse_relational_expression(self) -> ASTNode:
        expr = self._parse_additive_expression()

        while self._match(
            TokenType.OP_GT, TokenType.OP_LT, TokenType.OP_GTE,
            TokenType.OP_LTE, TokenType.OP_EQ, TokenType.OP_NEQ
        ):
            op_tok = self._previous()
            right = self._parse_additive_expression()
            expr = BinaryOpNode(
                line=op_tok.line,
                column=op_tok.column,
                left=expr,
                op=op_tok.value,
                right=right
            )
        return expr

    def _parse_additive_expression(self) -> ASTNode:
        expr = self._parse_multiplicative_expression()

        while self._match(TokenType.OP_ADD, TokenType.OP_SUB):
            op_tok = self._previous()
            right = self._parse_multiplicative_expression()
            expr = BinaryOpNode(
                line=op_tok.line,
                column=op_tok.column,
                left=expr,
                op=op_tok.value,
                right=right
            )
        return expr

    def _parse_multiplicative_expression(self) -> ASTNode:
        expr = self._parse_factor()

        while self._match(TokenType.OP_MUL, TokenType.OP_DIV, TokenType.OP_MOD):
            op_tok = self._previous()
            right = self._parse_factor()
            expr = BinaryOpNode(
                line=op_tok.line,
                column=op_tok.column,
                left=expr,
                op=op_tok.value,
                right=right
            )
        return expr

    def _parse_factor(self) -> ASTNode:
        if self._match(TokenType.OP_SUB):
            op_tok = self._previous()
            operand = self._parse_factor()
            return UnaryOpNode(
                line=op_tok.line,
                column=op_tok.column,
                op="-",
                operand=operand
            )

        if self._match(TokenType.INT_LITERAL):
            tok = self._previous()
            return LiteralNode(line=tok.line, column=tok.column, value=int(tok.value), data_type="int")

        if self._match(TokenType.FLOAT_LITERAL):
            tok = self._previous()
            return LiteralNode(line=tok.line, column=tok.column, value=float(tok.value), data_type="float")

        if self._match(TokenType.IDENTIFIER):
            tok = self._previous()
            return VarRefNode(line=tok.line, column=tok.column, name=tok.value)

        if self._match(TokenType.LPAREN):
            expr = self._parse_expression()
            self._consume(TokenType.RPAREN, "Expected ')' after expression")
            return expr

        tok = self._peek()
        err = SyntaxErrorRecord(f"Expected expression, found '{tok.value}'", tok.line, tok.column)
        self.errors.append(err)
        raise SyntaxError(str(err))